'use strict';

// Per-terminal output capture: size-capped rotation, tailing, and follow.
//
// A spawned terminal is fire-and-forget, so its output has to land somewhere
// durable enough to read after the fact and small enough that fifty of them
// cannot fill the disk. Each terminal owns one log path; rotation keeps
// `.1`, `.2`, `.3` and drops the rest, so a runaway build is bounded at
// maxBytes * (1 + maxFiles) rather than growing until the volume is full.

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

const DEFAULTS = {
  dir: process.env.OFFICE_HUD_TERMINAL_LOGS
    || path.join(os.tmpdir(), 'office-hud-terminals'),
  maxBytes: 10 * 1024 * 1024,
  maxFiles: 3,
  // A follow reader is capped so one client cannot hold the whole file in RAM.
  maxTailBytes: 512 * 1024,
};

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}

function logPath(id, options = {}) {
  const dir = options.dir || DEFAULTS.dir;
  // The id is generated by the manager, but a path built from caller input would
  // still be a traversal if that ever changed.
  if (!/^[A-Za-z0-9._-]+$/.test(String(id))) throw new Error(`unsafe terminal id: ${id}`);
  return path.join(dir, `${id}.log`);
}

function rotate(file, options = {}) {
  const maxFiles = options.maxFiles ?? DEFAULTS.maxFiles;
  const oldest = `${file}.${maxFiles}`;
  try { fs.rmSync(oldest, { force: true }); } catch { /* nothing to drop */ }
  for (let index = maxFiles - 1; index >= 1; index--) {
    const from = `${file}.${index}`;
    const to = `${file}.${index + 1}`;
    try { fs.renameSync(from, to); } catch { /* absent */ }
  }
  try { fs.renameSync(file, `${file}.1`); } catch { /* absent */ }
}

/** Append a chunk, rotating first if the write would cross the cap. */
function append(id, chunk, options = {}) {
  const file = logPath(id, options);
  const maxBytes = options.maxBytes ?? DEFAULTS.maxBytes;
  ensureDir(path.dirname(file));
  let size = 0;
  try { size = fs.statSync(file).size; } catch { size = 0; }
  if (size + chunk.length > maxBytes) rotate(file, options);
  try { fs.appendFileSync(file, chunk); } catch { return false; }
  return true;
}

/**
 * Read the tail of a log. Read from the end by byte offset rather than
 * splitting the whole file: a 10MB log tailed to 200 lines should not cost
 * 10MB of read plus a 200k-element array.
 */
function tail(id, options = {}) {
  const lines = Math.max(1, Math.min(Number(options.lines) || 200, 5000));
  const file = logPath(id, options);
  let handle = null;
  let size = 0;
  try {
    handle = fs.openSync(file, 'r');
    size = fs.fstatSync(handle).size;
  } catch {
    return { lines: [], truncated: false, bytes: 0, missing: true };
  }
  try {
    const windowBytes = Math.min(size, options.maxTailBytes ?? DEFAULTS.maxTailBytes);
    const buffer = Buffer.alloc(windowBytes);
    fs.readSync(handle, buffer, 0, windowBytes, size - windowBytes);
    const text = buffer.toString('utf8');
    const split = text.split('\n');
    // A window that starts mid-line yields a partial first line; drop it.
    if (size > windowBytes && split.length) split.shift();
    while (split.length && split[split.length - 1] === '') split.pop();
    const truncated = size > windowBytes;
    const kept = split.slice(-lines);
    return {
      lines: kept,
      truncated: truncated || split.length > lines,
      bytes: size,
      missing: false,
    };
  } finally {
    try { fs.closeSync(handle); } catch { /* already closed */ }
  }
}

/** Byte offset of the end, so a follower can read incrementally. */
function cursor(id, options = {}) {
  const file = logPath(id, options);
  try { return fs.statSync(file).size; } catch { return 0; }
}

/** Read whatever appeared after `from`, for SSE follow. */
function readSince(id, from, options = {}) {
  const file = logPath(id, options);
  let size = 0;
  try { size = fs.statSync(file).size; } catch { return { chunk: '', at: from || 0 }; }
  const start = Math.max(0, Math.min(Number(from) || 0, size));
  if (size === start) return { chunk: '', at: size };
  const want = Math.min(size - start, DEFAULTS.maxTailBytes);
  let handle = null;
  try {
    handle = fs.openSync(file, 'r');
    const buffer = Buffer.alloc(want);
    fs.readSync(handle, buffer, 0, want, start);
    return { chunk: buffer.toString('utf8'), at: start + want };
  } catch {
    return { chunk: '', at: start };
  } finally {
    try { if (handle !== null) fs.closeSync(handle); } catch { /* already closed */ }
  }
}

/** Remove a log and its rotations. Missing files are not an error. */
function remove(id, options = {}) {
  const file = logPath(id, options);
  const maxFiles = options.maxFiles ?? DEFAULTS.maxFiles;
  const targets = [file];
  for (let index = 1; index <= maxFiles; index++) targets.push(`${file}.${index}`);
  for (const target of targets) {
    try { fs.rmSync(target, { force: true }); } catch { /* already gone */ }
  }
  return true;
}

/** Total bytes on disk across every log; feeds the health route. */
function usage(options = {}) {
  const dir = options.dir || DEFAULTS.dir;
  let entries = [];
  try { entries = fs.readdirSync(dir); } catch { return { files: 0, bytes: 0 }; }
  let bytes = 0;
  for (const name of entries) {
    try { bytes += fs.statSync(path.join(dir, name)).size; } catch { /* raced with reap */ }
  }
  return { files: entries.length, bytes };
}

module.exports = { DEFAULTS, ensureDir, logPath, append, tail, cursor, readSince, remove, usage, rotate };